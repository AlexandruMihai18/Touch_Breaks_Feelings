from __future__ import annotations
import torch
import numpy as np
from PIL import Image

# Import the exact dataclass used in the DINO codebase
from dino.dataset import DinoSample

# Your original prompt
VISUAL_PROMPT_WITHOUT_AUDIO = """
You are given an image.
    
Task:
Determine whether the image contains a clear physical touch or contact event between two objects, two people, or a person and an object. 

Examples of touch/contact:
- Holding, grabbing, pushing, hugging
- Hand touching an object
- Physical interaction with surfaces or tools
- Collision or impact

Output rules:
- Return only:
    1 = physical touch/contact is present
    0 = no physical touch/contact is visible
- Do not explain your answer.
- If the contact is ambiguous or unclear, return 0.
"""

VISUAL_PROMPT_POINT_OF_TOUCH = """
You are given an image.
Task:
Identify the point of physical touch or contact in the image, if present.
Output rules:
- If physical touch is present, return the normalized coordinates of the point of contact in the format (x, y) where x and y are between 0.000 and 1.000.
- If no physical touch/contact is visible, or it is ambiguous, return (0.000, 0.000).
- Do not explain your answer.
"""

class QwenTouchCollator:
    def __init__(self, processor, task: str = "binary"):
        self.processor = processor
        self.task = task

    def _extract_normalized_point(self, sample: DinoSample, orig_width: int, orig_height: int) -> str:
        """Extracts [X, Y] from the segmentation mask, exactly matching DINO's logic."""
        if not sample.target_path or sample.label == 0:
            return "(0.000, 0.000)"
        
        try:
            mask = np.array(Image.open(sample.target_path).convert("L"))
            ys, xs = np.nonzero(mask > 0)
            if len(xs) == 0:
                return "(0.000, 0.000)"

            mean_x, mean_y = xs.mean(), ys.mean()
            distances = (xs - mean_x) ** 2 + (ys - mean_y) ** 2
            point_idx = int(np.argmin(distances))
            
            # Normalize to 0.0 - 1.0 based on ORIGINAL dimensions
            x_norm = float(xs[point_idx]) / max(orig_width - 1, 1)
            y_norm = float(ys[point_idx]) / max(orig_height - 1, 1)

            return f"({x_norm:.3f}, {y_norm:.3f})"
        
        except OSError:
            return "(0.000, 0.000)"

    def __call__(self, features: list[DinoSample]):
        """
        Accepts a list of DinoSample objects generated by dino.dataset.load_splits.
        """
        texts = []
        images = []
        prompt_lengths = []

        prompt = VISUAL_PROMPT_POINT_OF_TOUCH if self.task == "point" else VISUAL_PROMPT_WITHOUT_AUDIO

        for sample in features:
            image = Image.open(sample.image_path).convert("RGB")
            orig_width, orig_height = image.size
            image.thumbnail((768, 768), Image.Resampling.LANCZOS)
            
            label_text = self._extract_normalized_point(sample, orig_width, orig_height) if self.task == "point" else str(sample.label)

            messages = [
                {
                    "role": "user",
                    "content": [
                        {"type": "image", "image": image},
                        {"type": "text", "text": prompt},
                    ],
                },
                {
                    "role": "assistant",
                    "content": [{"type": "text", "text": label_text}],
                },
            ]

            text = self.processor.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=False
            )
            texts.append(text)
            images.append(image)

            prompt_only = [messages[0]]
            prompt_text = self.processor.apply_chat_template(prompt_only, tokenize=False, add_generation_prompt=True)
            prompt_inputs = self.processor(text=[prompt_text], images=[image], return_tensors="pt")
            prompt_lengths.append(prompt_inputs["input_ids"].shape[1])

        batch = self.processor(
            text=texts,
            images=images,
            return_tensors="pt",
            padding=True,
        )
        labels = batch["input_ids"].clone()
        
        # 3. ADDED: Safely mask padding AND prompt tokens (Handles Left/Right Padding)
        for i, p_len in enumerate(prompt_lengths):
            pad_mask = batch["attention_mask"][i] == 1
            actual_token_indices = pad_mask.nonzero(as_tuple=True)[0]
            
            if len(actual_token_indices) >= p_len:
                # Mask the user prompt tokens
                prompt_indices = actual_token_indices[:p_len]
                labels[i, prompt_indices] = -100
            
            # Mask padding
            if self.processor.tokenizer.pad_token_id is not None:
                labels[i, batch["input_ids"][i] == self.processor.tokenizer.pad_token_id] = -100

        batch["labels"] = labels
        return batch